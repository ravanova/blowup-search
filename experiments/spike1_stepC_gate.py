"""Spike 1 Step C: relax the rescaled 2D Boussinesq system to the Chen-Hou self-similar
profile and test the PRE-COMMITTED gauge-honest predicate.

GAUGE NOTE (the anti-self-deception point): the normalization (2.11)/(2.12) FREEZES
theta_xx(0), omega_x(0) at their initial values, so c_l = 2 theta_xx(0)/omega_x(0) is an
INPUT we set, not a result. We pin the Chen-Hou gauge (c_l = 3.006499 via theta_xx(0)/
omega_x(0) = 1.5032) so the comparison is apples-to-apples. The real, gauge-INVARIANT tests:

  PRE-COMMITTED PREDICATE (locked before the logged run; user-approved 2026-07-25):
    1. alpha = c_omega/c_l -> -0.3424 +-5%   (equiv. c_omega -> -1.0294 at the pinned c_l)
    2. far-field omega(r,beta*) ~ r^alpha over >=1 decade, fitted exponent within ~10%
    3. profile shape: single-signed, anisotropy |omega_y| < 0.23 |omega_x|, sane angular g1
    4. resolution/domain-stable (refine n_r,n_beta; extend r_max; incl. r_min inner BC)
  Else -> honest negative, reported with the reason.

This script runs EXPLORATORY by default (short, non-logged, for stability/convergence
tuning). The logged gate run (--logged) does the resolution study + commits data + figure.
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from solver.boussinesq_velocity import PolarGrid  # noqa: E402
from solver.boussinesq_rescaled import (  # noqa: E402
    RescaledBoussinesq, CL_STAR, COMEGA_STAR, ALPHA_STAR,
)


def profile_ansatz(grid, alpha=ALPHA_STAR, wx0=1.0, cl=CL_STAR):
    """Initial guess pinning the Chen-Hou gauge and baking in the r^alpha far field.
    omega, eta odd in x (~ slope*x near 0 via the r*cos(beta) factor, ~r^alpha / r^{2alpha}
    far field); xi starts at 0 and is generated by the -u_y eta coupling. The origin slopes
    set the frozen gauge: omega_x(0)=wx0, theta_xx(0)=eta_x(0)=cl/2*wx0 => c_l = cl."""
    r = grid.R
    cb = np.cos(grid.B)
    thxx0 = 0.5 * cl * wx0                       # so 2 thxx0/wx0 = cl
    env_odd = r / (1.0 + r ** (1.0 - alpha))     # ~r near 0, ~r^alpha far
    env_eta = r / (1.0 + r ** (1.0 - 2 * alpha)) # ~r near 0, ~r^{2alpha} far
    omega = wx0 * env_odd * cb
    eta = thxx0 * env_eta * cb
    xi = np.zeros_like(r)
    return omega, eta, xi


def radial_exponent(field, grid, k_beta=None, r_lo=1e1, r_hi=1e3):
    """Fit d log|field| / d log r at a fixed angular index over [r_lo, r_hi] (far field)."""
    if k_beta is None:
        k_beta = grid.n_beta // 2
    col = np.abs(field[:, k_beta])
    m = (grid.r > r_lo) & (grid.r < r_hi) & (col > 0)
    if m.sum() < 5:
        return np.nan
    p = np.polyfit(np.log(grid.r[m]), np.log(col[m]), 1)
    return p[0]


def run_case(n_r, n_beta, r_min, r_max, max_steps, tol, dt_frac=0.25, verbose=False):
    grid = PolarGrid(n_r=n_r, n_beta=n_beta, r_min=r_min, r_max=r_max)
    om0, et0, xi0 = profile_ansatz(grid)
    solver = RescaledBoussinesq(grid)
    res = solver.run(om0, et0, xi0, dt_frac=dt_frac, tol=tol, max_steps=max_steps,
                     verbose=verbose)
    res["grid"] = grid
    res["alpha"] = res["c_omega"] / res["c_l"] if res["c_l"] else np.nan
    res["alpha_radial"] = radial_exponent(res["omega"], grid,
                                          r_lo=r_max ** 0.35, r_hi=r_max ** 0.75)
    return res


def _report(res, label):
    print(f"[{label}] steps={res['steps']:5d} tau={res['tau']:8.2f} res={res['residual']:.2e} "
          f"conv={res['converged']}")
    print(f"    c_l={res['c_l']:+.5f} (target {CL_STAR:+.5f})  "
          f"c_omega={res['c_omega']:+.5f} (target {COMEGA_STAR:+.5f})")
    print(f"    alpha=c_omega/c_l={res['alpha']:+.5f} (target {ALPHA_STAR:+.5f})  "
          f"alpha_radial(fit)={res['alpha_radial']:+.5f}")


