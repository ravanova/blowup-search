"""Spike 1 Step C: relax the rescaled 2D Boussinesq system to the Chen-Hou self-similar
profile and test the PRE-COMMITTED gauge-honest predicate.

GAUGE NOTE (the anti-self-deception point): the normalization (2.11)/(2.12) FREEZES
theta_xx(0), omega_x(0) at their initial values, so c_l = 2 theta_xx(0)/omega_x(0) is an
INPUT we set, not a result. We pin the Chen-Hou gauge (c_l = 3.006499 via theta_xx(0)/
omega_x(0) = 1.5032) so the comparison is apples-to-apples. The real, gauge-INVARIANT tests:

  PRE-COMMITTED PREDICATE (locked before the logged run; user-approved 2026-07-25):
    1. alpha = c_omega/c_l -> -0.3424 +-5%   (equiv. c_omega -> -1.0294 at the pinned c_l)
    2. far-field omega(r,beta*) ~ r^alpha over >=1 decade, fitted exponent within ~10%
    3. profile shape: single-signed, anisotropy |omega_y| < 0.23 |omega_x|, sane angular g1
    4. resolution/domain-stable (refine n_r,n_beta; extend r_max; incl. r_min inner BC)
  Else -> honest negative, reported with the reason.

This script runs EXPLORATORY by default (short, non-logged, for stability/convergence
tuning). The logged gate run (--logged) does the resolution study + commits data + figure.
"""

