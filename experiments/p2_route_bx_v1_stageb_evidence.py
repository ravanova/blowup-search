"""Phase-2 Route-BX v1: render the stage-`B` closure audit from committed data.

NO FIGURE, BY DESIGN.  This leg measures no corner -- its gate answered NO -- and the
repository's convention (Route-D, "no measurement, no figure") is that an assembly/audit
leg that measures nothing registers no figure.  The audit's deliverable is a LEDGER, and a
ledger is read, not plotted, so this evidence runner prints it.

Nothing is recomputed here.  Every number comes from `writeup/data/p2_route_bx_v1_stageb.json`,
which is regenerated by:
    .venv/bin/python -u experiments/p2_route_bx_v1_stageb.py

Run:
    .venv/bin/python experiments/p2_route_bx_v1_stageb_evidence.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "writeup" / "data" / "p2_route_bx_v1_stageb.json"


def rule(ch="-", n=78):
    print(ch * n)


def main():
    if not SRC.exists():
        print(f"missing {SRC.relative_to(ROOT)} -- run p2_route_bx_v1_stageb.py first")
        return 1
    with open(SRC) as fh:
        d = json.load(fh)

    rule("=")
    print("ROUTE-BX v1 -- STAGE B, ANSWERED FROM THE BANKED RECORD: THE CLOSURE AUDIT")
    rule("=")
    print(f"object : {d['object']}")
    print(f"novelty: {d['BX0_novelty']['verdict']}  ({d['BX0_novelty']['log']})")
    print()

    # -- BX1 -----------------------------------------------------------------
    print("BX1  STAGE B'S DECLARED SEARCH SPACE, ENUMERATED BEFORE THE COVERING CHECK")
    rule()
    for axis, vals in d["BX1_declared_axes"].items():
        print(f"  {axis:16s} : {vals}")
    print(f"  operator mu held at {d['BX1_operator_mu_held_at']} "
          f"(mu is NOT an axis of B; it is BX3's control)")
    print()

    # -- BX2 -----------------------------------------------------------------
    print("BX2  THE BANKED CLAUSES")
    rule()
    print(f"  {'id':18s} {'leg':>4s}  {'type':11s} headline magnitude")
    rule()
    for c in d["BX2_clauses"]:
        mag = c["magnitude"]
        k0 = next(iter(mag))
        v0 = mag[k0]
        vs = f"{v0:.6g}" if isinstance(v0, (int, float)) else str(v0)
        print(f"  {c['id']:18s} {c['leg']:>4d}  {c['type']:11s} {k0} = {vs}")
    print()
    print(f"  configurations enumerated : {d['BX2_n_configurations']}")
    print(f"  covered                   : {d['BX2_n_covered']}")
    print(f"  UNCOVERED                 : {d['BX2_n_uncovered']}")
    print(f"  by strongest coverage     : {d['BX2_by_strongest_coverage']}")
    print()

    # -- BX3 -----------------------------------------------------------------
    print("BX3  CONTROLS -- THE PREDICATE MUST BE ABLE TO SAY 'NOT COVERED'")
    rule()
    ins = d["BX3_instrument_check"]
    print(f"  instrument vs leg 54: block_diag {ins['block_diag_recomputed']:.6f} vs "
          f"{ins['block_diag_banked']:.6f} (rel {ins['block_diag_rel_gap']:.2e})")
    print(f"                        ff_lift    {ins['ff_lift_recomputed']:.6f} vs "
          f"{ins['ff_lift_banked']:.6f} (rel {ins['ff_lift_rel_gap']:.2e})")
    pos = d["BX3_positive_control"]
    print(f"  positive control ({pos['n_dial_entries_checked']} entries, max rel gap vs "
          f"leg 58 = {pos['max_rel_gap_vs_leg58']:.2e}):")
    print(f"    {'mu':>5s} {'class':10s} {'shape':11s} {'Z1':>12s}  closes  covered_by")
    for r in pos["rows"]:
        print(f"    {r['mu']:5.1f} {r['class']:10s} {r['shape']:11s} {r['Z1']:12.6f}  "
              f"{str(r['closes']):6s}  {','.join(r['covered_by']) or 'NOT COVERED'}")
    print(f"  predicate discriminates   : {pos['predicate_discriminates']}")
    print(f"  first draft's WRONG realization gave {pos['first_draft_wrong_realization_gave']} "
          f"({pos['first_draft_error_factor']:.0f}x off)")
    print()

    # -- BX4 -----------------------------------------------------------------
    print("BX4  THE SPACE AXIS IS A PARTITION, WITH NO GAP")
    rule()
    for reg in d["BX4_space_partition"]["regions"]:
        print(f"  {reg['range']:28s} {reg['status']:14s} {reg['covered_by']}")
    print(f"  gap: {d['BX4_space_partition']['gap']}")
    print()

    # -- BX5 -----------------------------------------------------------------
    print("BX5  COVERAGE GAP vs PROOF-STRENGTH GAP")
    rule()
    g = d["BX5_proof_strength_gap"]
    print(f"  where      : {g['where_it_is']}")
    print(f"  what it is : {g['what_it_is']}")
    for k, v in g["magnitudes"].items():
        print(f"    {k:34s} = {v:.6g}")
    print(f"  NOT a corner because: {g['why_it_is_NOT_a_stage_B_corner']}")
    print(f"  already routed      : {g['already_routed']}")
    print()

    # -- BX6 -----------------------------------------------------------------
    print("BX6  TUNING versus STRUCTURE -- THE NUMBER B'S NO-BRANCH ASKS FOR")
    rule()
    t = d["BX6_tuning_vs_structure"]
    print(f"  scale: {t['scale']}")
    print(f"    baseline (block-diagonal)      Z1 = {t['baseline_block_diagonal_Z1']:.6f}")
    print(f"    best over the whole battery    Z1 = "
          f"{t['best_admissible_Z1_over_whole_battery']:.6f}")
    print(f"    measured in-class floor        Z1 = {t['measured_in_class_floor_Z1']:.6f}")
    print(f"    required                       Z1 <  {t['required_Z1']:.1f}")
    print()
    print(f"    decades required               = {t['decades_required']:.6f}")
    print(f"    delivered by tuning            = {t['decades_delivered_by_tuning']:.6f}")
    print(f"    searchable headroom            = {t['decades_of_searchable_headroom']:.6f}")
    print(f"    left unrealized                = "
          f"{t['decades_of_headroom_left_unrealized']:.6f}")
    print(f"    owned by structure             = {t['decades_owned_by_structure']:.6f}")
    print()
    s = t["shares_of_the_requirement"]
    print(f"    tuning realized                = {s['tuning_realized']:.4%}")
    print(f"    tuning headroom unrealized     = {s['tuning_unrealized_headroom']:.4%}")
    print(f"    structure                      = {s['structure']:.4%}")
    print(f"    (sum = {t['shares_sum']:.12f})")
    print(f"    tuning reached {t['tuning_fraction_of_its_own_ceiling']:.4%} of its own ceiling")
    print(f"    a PERFECT search still leaves Z1 >= "
          f"{t['shortfall_if_search_were_PERFECT']:.4f}, i.e. "
          f"{t['shortfall_if_search_were_PERFECT']:.2f}x short")
    print()
    pg = t["proved_grade_accounting"]
    print(f"  PROVED-grade, on {pg['class']}:")
    print(f"    {pg['statement']}")
    print()

    rule("=")
    print(f"GATE: {d['gate_answer']}")
    print(f"  {d['gate_branch']}")
    print(f"  conditions failed: {d['gate_conditions_failed'] or 'none'}")
    rule("=")
    print(f"CEILING: {d['ceiling']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
