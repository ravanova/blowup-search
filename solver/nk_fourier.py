def ell1_op_norm(M):
    """Induced ell^1 -> ell^1 operator norm = max absolute COLUMN sum."""
    M = np.atleast_2d(np.asarray(M, dtype=float))
    return float(np.abs(M).sum(axis=0).max()) if M.size else 0.0


def weighted_ell1_op_norm(M, w_dom, w_cod):
    """Induced norm of M for ||x|| = sum w_dom_k |x_k|, ||y|| = sum w_cod_m |y_m|.

    ||M|| = max_k (1 / w_dom_k) * sum_m w_cod_m |M_mk|  (weighted column sums).
    """
    M = np.atleast_2d(np.asarray(M, dtype=float))
    if M.size == 0:
        return 0.0
    cols = (np.abs(M) * np.asarray(w_cod, dtype=float)[:, None]).sum(axis=0)
    return float((cols / np.asarray(w_dom, dtype=float)).max())


