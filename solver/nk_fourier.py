def radii_polynomial(Y0, Z0, Z1, Z2):
    """Standard radii-polynomial test p(r) = Z2 r^2 - (1 - Z0 - Z1) r + Y0.

    Returns a dict with the contraction budget `one_minus_Z`, the discriminant,
    whether the ball CLOSES (a positive root interval exists), the smaller root
    r_min (the certified radius), and -- the number this dress rehearsal is really
    after -- `Y0_max`, the LARGEST defect that would still close at these Z's:

        Y0_max = (1 - Z0 - Z1)^2 / (4 Z2).

    Y0_max is the "certification budget": compare it against the residual floor of
    an approximate profile to see whether certifying that profile is even
    arithmetically conceivable.
    """
    one_minus_Z = 1.0 - Z0 - Z1
    disc = one_minus_Z ** 2 - 4.0 * Z2 * Y0
    closes = bool(one_minus_Z > 0.0 and disc >= 0.0 and Z2 > 0.0)
    r_min = float((one_minus_Z - np.sqrt(disc)) / (2.0 * Z2)) if closes else float("nan")
    r_max = float((one_minus_Z + np.sqrt(disc)) / (2.0 * Z2)) if closes else float("nan")
    Y0_max = float(one_minus_Z ** 2 / (4.0 * Z2)) if (one_minus_Z > 0 and Z2 > 0) else 0.0
    return {
        "Y0": float(Y0), "Z0": float(Z0), "Z1": float(Z1), "Z2": float(Z2),
        "one_minus_Z": float(one_minus_Z), "discriminant": float(disc),
        "closes": closes, "r_min": r_min, "r_max": r_max, "Y0_max": Y0_max,
    }


