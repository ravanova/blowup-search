def tail_band(k, c=C_ANCHOR):
    """The three exact DF entries of far-field column k, at the anchor.

    With Omega_2 = -1/2 - (1/2) cos and H(Omega_2) = -(1/2) sin, column k of
    DF collects, mode by mode,

      term (i)   cos(k) H(Omega_2) :  m=k+1 -> -1/4,  m=k-1 -> +1/4
      term (ii)  Omega_2 sin(k)    :  m=k   -> -1/2,  m=k+-1 -> -1/4
      term (iii) transport c k     :  m=k   -> +c k,  m=k+-1 -> +c k / 2

    so the column is (sub, diag, sup) = (c k / 2,  c k - 1/2,  c k / 2 - 1/2)
    on rows (k-1, k, k+1) and ZERO elsewhere -- the tridiagonality of Route-D v1
    Q4, now in closed form rather than as a grid cross-check.
    """
    k = int(k)
    return (0.5 * c * k, c * k - 0.5, 0.5 * c * k - 0.5)


def tail_Z1_column(k, c=C_ANCHOR, diag="transport"):
    """ell^1 column weight of A_tail (A_dagger - DF) at far-field mode k.

    The finite-section NK recipe approximates the far field of DF by its diagonal
    Lambda and sets A_tail = diag(1/Lambda_m); everything discarded then lands in
    Z1 = ||A (A_dagger - DF)||.  With the exact band of `tail_band`, column k
    contributes

        z(k) = |sub| / |Lambda_{k-1}| + |sup| / |Lambda_{k+1}|.

    Two natural choices of Lambda bracket the answer:
      diag="transport"  Lambda_m = c m           (the pure transport diagonal)
          z(k) = (c k / 2)/(c (k-1)) + (c k / 2 - 1/2)/(c (k+1))  ->  1 FROM BELOW
      diag="exact"      Lambda_m = c m - 1/2     (the true DF diagonal)
          z(k) = (c k / 2)/(c(k-1) - 1/2) + (c k / 2 - 1/2)/(c(k+1) - 1/2)
                                                 ->  1 FROM ABOVE

    BOTH tend to 1, from opposite sides, at rate O(1/k), and the limit is
    independent of c.  That is the whole story: the far field is EXACTLY MARGINAL.
    The reason is structural -- the transport term is c (1 + cos theta) d_theta and
    the symbol 1 + cos(phi) has ell^1 norm 2, exactly twice its own mean, because
    it VANISHES at phi = pi (i.e. at X = infinity).  Whatever the truncation N,
    sup_{k>N} z(k) = 1, so 1 - Z0 - Z1 <= 0 and the radii polynomial cannot close.
    Sharpening the tail model does not help (`tail_weight_obstruction`): it only
    moves the divergence from Z1 into ||A||.
    """
    k = int(k)
    if k < 2:
        raise ValueError("tail column analysis applies to k >= 2")
    sub, _, sup = tail_band(k, c)
    if diag == "transport":
        lo, hi = c * (k - 1), c * (k + 1)
    elif diag == "exact":
        # the TRUE diagonal c m - 1/2 vanishes at m = 1/(2c) (m = 1 for c = 1/2),
        # so this model only describes the far field, k >= 1/(2c) + 2
        if c * (k - 1) - 0.5 <= 0.0:
            raise ValueError(f"exact-diagonal tail model needs k > {0.5 / c + 1:g}")
        lo, hi = c * (k - 1) - 0.5, c * (k + 1) - 0.5
    else:
        raise ValueError(f"unknown diag model {diag!r}")
    return float(abs(sub) / abs(lo) + abs(sup) / abs(hi))


def tail_weight_obstruction(w, k_lo, k_hi, c=C_ANCHOR):
    """Weighted-ell^1 version of `tail_Z1_column`, for a domain weight w(k).

    With weight w the column weight becomes

        z_w(k) = [ w(k-1) k / (2 (k-1)) + w(k+1) k / (2 (k+1)) ] / w(k)
               = ( u(k-1) + u(k+1) ) / (2 u(k)),      u(k) := w(k) / k.

    (up to the O(1/k) corrections of `tail_band`, which do not change the limit).
    z_w(k) <= 1 - delta for all large k forces u(k+1) <= 2(1-delta) u(k) - u(k-1);
    that recursion's characteristic roots (1-delta) +- i sqrt(1 - (1-delta)^2) sit
    ON the unit circle with argument arccos(1-delta) > 0, so every solution
    oscillates and any positive sequence obeying it must change sign in finitely
    many steps.  Hence NO positive weight achieves a uniform Z1 < 1: the best
    possible is u affine (w(k) = k(alpha + beta k)), which gives z_w == 1 exactly.
    Returns the sup of z_w over [k_lo, k_hi] so an experiment can display it.
    """
    ks = np.arange(int(k_lo), int(k_hi) + 1)
    u = np.array([w(int(k)) / k for k in range(int(k_lo) - 1, int(k_hi) + 2)])
    z = (u[:-2] + u[2:]) / (2.0 * u[1:-1])
    return float(np.max(z)), ks, z
